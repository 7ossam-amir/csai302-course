"""Observe PostgreSQL's real WAL, checkpoints, trigger-based auditing, and crash recovery.

Modes (run from the repository root with the course .venv):

    settings      durability-related settings and the current WAL position
    wal           WAL bytes generated by a logged table versus an UNLOGGED table
    checkpoint    pg_control_checkpoint() before and after CHECKPOINT
    audit         a committed and a rolled-back transfer, and the audit rows each leaves
    crash-prepare commit one marker row, hold a second uncommitted, wait for a server kill
    crash-check   after the restart: which markers survived, and where to read the redo log
    all           settings, wal, checkpoint, audit (never the crash modes)
"""

import argparse
import os
import time
from pathlib import Path

try:
    import psycopg
except ModuleNotFoundError:
    psycopg = None

try:
    from dotenv import load_dotenv
except ModuleNotFoundError:
    load_dotenv = None


REPO_ROOT = Path(__file__).resolve().parents[2]
if load_dotenv is not None:
    load_dotenv(REPO_ROOT / ".env")

CONNECTION = {
    "host": os.getenv("POSTGRES_HOST", "localhost"),
    "port": os.getenv("POSTGRES_PORT", "5432"),
    "dbname": os.getenv("POSTGRES_DB", "csai302"),
    "user": os.getenv("POSTGRES_USER", "csai302"),
    "password": os.getenv("POSTGRES_PASSWORD", ""),
}

SETTINGS = [
    "wal_level", "fsync", "synchronous_commit", "full_page_writes", "wal_sync_method",
    "wal_buffers", "checkpoint_timeout", "max_wal_size", "checkpoint_completion_target",
    "archive_mode",
]


def _connect(*, autocommit: bool = True):
    if psycopg is None:
        raise RuntimeError("Psycopg 3 is missing; install the course requirements in the existing .venv")
    return psycopg.connect(**CONNECTION, autocommit=autocommit, connect_timeout=5)


def _require_fixture(connection) -> None:
    found = connection.execute("SELECT to_regclass('lab08.accounts') IS NOT NULL").fetchone()[0]
    if not found:
        raise RuntimeError("Lab 8 schema is missing; run db/schema.sql and db/seed.sql first")


def show_settings() -> None:
    print("== Durability settings")
    with _connect() as connection:
        for name in SETTINGS:
            value = connection.execute(f"SHOW {name}").fetchone()[0]
            print(f"  {name:<30} {value}")
        lsn, walfile = connection.execute(
            "SELECT pg_current_wal_lsn(), pg_walfile_name(pg_current_wal_lsn())"
        ).fetchone()
        print(f"  current WAL LSN                {lsn}  (segment file {walfile})")


def _wal_bytes_for_insert(connection, table: str, rows: int) -> int:
    connection.execute(f"TRUNCATE {table}")
    start = connection.execute("SELECT pg_current_wal_insert_lsn()").fetchone()[0]
    with connection.transaction():
        connection.execute(
            f"INSERT INTO {table} (id, payload) "
            "SELECT g, repeat(md5(g::text), 4) FROM generate_series(1, %s) AS g",
            (rows,),
        )
    return connection.execute(
        "SELECT pg_wal_lsn_diff(pg_current_wal_insert_lsn(), %s)::bigint", (start,)
    ).fetchone()[0]


def wal_volume(rows: int = 20_000) -> None:
    print(f"\n== WAL generated by inserting {rows:,} rows")
    with _connect() as connection:
        _require_fixture(connection)
        logged = _wal_bytes_for_insert(connection, "lab08.wal_logged", rows)
        unlogged = _wal_bytes_for_insert(connection, "lab08.wal_unlogged", rows)
        size = connection.execute(
            "SELECT pg_total_relation_size('lab08.wal_logged')"
        ).fetchone()[0]
    print(f"  logged table     {logged:>12,} WAL bytes   (table + index size {size:,} bytes)")
    print(f"  UNLOGGED table   {unlogged:>12,} WAL bytes")
    print("  An UNLOGGED table skips WAL for its data, so it is faster to load but is")
    print("  truncated during crash recovery and is not sent to streaming replicas.")


def checkpoint_effect() -> None:
    print("\n== Checkpoint: control-file fields before and after CHECKPOINT")
    query = ("SELECT checkpoint_lsn, redo_lsn, redo_wal_file, checkpoint_time "
             "FROM pg_control_checkpoint()")
    with _connect() as connection:
        _require_fixture(connection)
        before = connection.execute(query).fetchone()
        with connection.transaction():
            connection.execute(
                "INSERT INTO lab08.wal_logged (id, payload) "
                "SELECT g, 'dirty page ' || g FROM generate_series(1000001, 1005000) AS g "
                "ON CONFLICT (id) DO UPDATE SET payload = EXCLUDED.payload"
            )
        dirty = connection.execute(
            "SELECT count(*) FROM pg_buffercache WHERE isdirty"
        ).fetchone()[0] if _has_extension(connection, "pg_buffercache") else None
        try:
            connection.execute("CHECKPOINT")
        except psycopg.errors.InsufficientPrivilege:
            print("  CHECKPOINT needs superuser or the pg_checkpoint role; showing current values only")
        after = connection.execute(query).fetchone()
        stats = connection.execute(
            "SELECT num_timed, num_requested, buffers_written FROM pg_stat_checkpointer"
        ).fetchone()
    for label, row in (("before", before), ("after ", after)):
        print(f"  {label}: checkpoint_lsn={row[0]}  redo_lsn={row[1]}  file={row[2]}  at {row[3]:%H:%M:%S}")
    if dirty is not None:
        print(f"  dirty shared buffers just before CHECKPOINT: {dirty}")
    print(f"  pg_stat_checkpointer: timed={stats[0]} requested={stats[1]} buffers_written={stats[2]}")
    print("  redo_lsn is where crash recovery would begin replaying WAL; older WAL")
    print("  segments become recyclable (unless archiving or replication still needs them).")


def _has_extension(connection, name: str) -> bool:
    return connection.execute(
        "SELECT EXISTS (SELECT 1 FROM pg_extension WHERE extname = %s)", (name,)
    ).fetchone()[0]


def _transfer(connection, app_user: str, amount: int, *, commit: bool) -> None:
    with connection.transaction():
        connection.execute("SELECT set_config('lab08.app_user', %s, true)", (app_user,))
        connection.execute("UPDATE lab08.accounts SET balance = balance - %s WHERE id = 1", (amount,))
        connection.execute("UPDATE lab08.accounts SET balance = balance + %s WHERE id = 2", (amount,))
        if not commit:
            raise psycopg.Rollback()  # leaves the block quietly, without committing


def audit_demo() -> None:
    print("\n== Audit trigger: one committed and one rolled-back transfer")
    with _connect() as connection:
        _require_fixture(connection)
        connection.execute("UPDATE lab08.accounts SET balance = 1000 WHERE id IN (1, 2)")
        connection.execute("TRUNCATE lab08.audit_log RESTART IDENTITY")  # drop the reset's rows
        _transfer(connection, "alice", 100, commit=True)
        _transfer(connection, "bob", 300, commit=False)
        balances = connection.execute(
            "SELECT id, balance FROM lab08.accounts WHERE id IN (1, 2) ORDER BY id"
        ).fetchall()
        rows = connection.execute(
            "SELECT audit_id, app_user, db_user, xact_id, operation, row_id, "
            "old_row->>'balance', new_row->>'balance' FROM lab08.audit_log ORDER BY audit_id"
        ).fetchall()
    print(f"  balances now: {dict(balances)}")
    for audit_id, app_user, db_user, xact, op, row_id, old, new in rows:
        print(f"  #{audit_id} xact {xact} {op} account {row_id}: {old} -> {new} "
              f"(app user {app_user}, db user {db_user})")
    print(f"  {len(rows)} audit rows: alice's committed transfer only. bob's audit rows were")
    print("  written in the same transaction, so ROLLBACK removed them with the data change.")


def crash_prepare(wait_seconds: int) -> None:
    print("== Crash preparation")
    with _connect() as connection:
        _require_fixture(connection)
        connection.execute("INSERT INTO lab08.crash_markers (label) VALUES ('committed-before-crash')")
    print("  committed marker 'committed-before-crash'")
    holder = _connect(autocommit=False)
    try:
        holder.execute("INSERT INTO lab08.crash_markers (label) VALUES ('uncommitted-at-crash')")
        holder.execute("SELECT pg_current_wal_flush_lsn()")
        print("  inserted 'uncommitted-at-crash' in an open transaction (not committed)")
        print("\n  Now kill the server from another terminal at the repository root:")
        print("    docker compose --env-file .env -f infra/compose.yaml kill -s KILL postgres")
        print(f"  Waiting up to {wait_seconds} s for the connection to drop...")
        deadline = time.monotonic() + wait_seconds
        while time.monotonic() < deadline:
            time.sleep(1)
            holder.execute("SELECT 1")
        print("  The server is still up; rolling back. Nothing was crashed.")
        holder.rollback()
    except psycopg.OperationalError as failure:
        print(f"  connection lost as expected: {str(failure).splitlines()[0]}")
        print("\n  Start the server again, then run --mode crash-check:")
        print("    docker compose --env-file .env -f infra/compose.yaml start postgres")
    finally:
        holder.close()


def crash_check() -> None:
    print("== After restart")
    with _connect() as connection:
        _require_fixture(connection)
        labels = [row[0] for row in connection.execute(
            "SELECT label FROM lab08.crash_markers ORDER BY id").fetchall()]
        redo = connection.execute("SELECT redo_lsn, checkpoint_time FROM pg_control_checkpoint()").fetchone()
        started = connection.execute("SELECT pg_postmaster_start_time()").fetchone()[0]
    print(f"  markers present: {labels or 'none'}")
    print(f"  committed marker survived:   {'committed-before-crash' in labels}")
    print(f"  uncommitted marker survived: {'uncommitted-at-crash' in labels}")
    print(f"  server started at {started:%H:%M:%S}; latest checkpoint redo_lsn {redo[0]}")
    print("  Read the recovery messages (look for 'was interrupted', 'redo starts at', 'redo done at'):")
    print("    docker compose --env-file .env -f infra/compose.yaml logs --tail 40 postgres")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--mode", default="all", choices=[
        "settings", "wal", "checkpoint", "audit", "crash-prepare", "crash-check", "all"])
    parser.add_argument("--wait", type=int, default=90, help="crash-prepare wait in seconds")
    args = parser.parse_args()
    try:
        if args.mode in ("settings", "all"):
            show_settings()
        if args.mode in ("wal", "all"):
            wal_volume()
        if args.mode in ("checkpoint", "all"):
            checkpoint_effect()
        if args.mode in ("audit", "all"):
            audit_demo()
        if args.mode == "crash-prepare":
            crash_prepare(args.wait)
        if args.mode == "crash-check":
            crash_check()
    except (RuntimeError, OSError) as problem:
        raise SystemExit(f"PostgreSQL demo stopped: {problem}") from None
    except Exception as problem:  # psycopg errors: keep the message short for students
        if psycopg is not None and isinstance(problem, psycopg.Error):
            raise SystemExit(f"PostgreSQL demo stopped: {problem}") from None
        raise


if __name__ == "__main__":
    main()
