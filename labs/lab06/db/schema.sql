CREATE SCHEMA IF NOT EXISTS lab06;

CREATE TABLE IF NOT EXISTS lab06.customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name text NOT NULL,
    segment text NOT NULL CHECK (segment IN ('standard', 'plus', 'business')),
    created_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS lab06.orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES lab06.customers(id),
    status text NOT NULL CHECK (status IN ('paid', 'shipped', 'pending', 'cancelled')),
    total_amount numeric(10, 2) NOT NULL CHECK (total_amount >= 0),
    placed_at timestamptz NOT NULL
);

-- The primary-key indexes are created with their constraints. Status and
-- customer_id lookup indexes are added only in db/indexes.sql for the experiment.
